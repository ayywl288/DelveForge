package com.ayywl.delveforge.application.repositoryanalysis.scout;

/**
 * 一次 Scout Provider 调用的许可。
 *
 * <pre>
 * Scout 每次真正要发出请求之前，先向调用方要一个许可
 *         ↓
 * 调用方在这里判定预算：不允许就抛出 → **这一次调用不会发生**
 * </pre>
 *
 * <h2>为什么重试也要许可</h2>
 *
 * <p>重试是一次**真实的模型调用**，不是一次内部重放。把它记在「逻辑上的 Scout 阶段数」里
 * 会让成本不可见：一次分析看起来只问了 7 次，实际可能问了 9 次。
 * 因此许可在**每一次尝试之前**申请，包括重试那一次——预算不允许时，重试不会发出。
 *
 * <h2>它由调用方提供，不由本层自己判定</h2>
 *
 * <p>「这次分析还剩几次额度」是**调用链的状态**，不是一次调用的属性：同一个
 * {@code RepositoryScoutExtraction} 既服务 flat 路径的单次调用，也服务分层路径下每个终态组。
 * 因此许可由持有计数的那一方给出，本层只负责「按许可发请求」。
 *
 * <h2>抛什么由调用方决定</h2>
 *
 * <p>接口只说「不许可时抛出」。分层导航抛它的导航预算异常，分支执行抛 Scout 调用总数异常——
 * 失败语义留在知道上下文的那一层，与既有的守卫写法一致。
 *
 * <p>生产链路上的实现必须真的记账。测试与不设预算的独立工具可以直接给出空实现
 * （{@code () -> { }}），它们本来就没有预算可记。
 */
@FunctionalInterface
public interface ScoutAttemptPermit {

    /**
     * 申请一次 Provider 调用的许可。
     *
     * @throws RuntimeException 预算不允许时由调用方抛出；抛出即表示这一次调用不得发出
     */
    void acquire();
}
